"""Restore and rehash real weight, dataset-reference and history bytes in private scratch."""
from datetime import datetime, timezone
import importlib.util
import json
from pathlib import Path
import shutil
import tempfile

PHASE = Path(__file__).resolve().parent
REPO = PHASE.parents[3]


def main():
    assert not (PHASE / "RESTORE_CHECKS.json").exists()
    base = json.loads((PHASE / "BASELINE.json").read_text(encoding="utf-8"))
    package = Path(base["package_destination"])
    spec = importlib.util.spec_from_file_location("a5_restore_reader", PHASE / "updates/scripts/migration/content_bundle.py")
    bundle = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bundle)
    source_rows = bundle.read_rows(package / "SOURCE_FILES.jsonl")
    # This directory is newly generated by this check; never point cleanup at source roots.
    scratch = Path(tempfile.mkdtemp(prefix="a5-restore-check-", dir=PHASE)).resolve()
    assert scratch.is_relative_to(PHASE.resolve()) and scratch.parent == PHASE.resolve()
    results = []
    success = False
    try:
        cases = [("weights", "rap-main", "weights/"),
                 ("dataset-reference", "datasets", "data_odometry_velodyne/dataset/poses/"),
                 ("external-history", "codex-records", "2026-09-17/")]
        for name, root, prefix in cases:
            target = scratch / name
            result = bundle.restore_files(package, target, root=root, prefix=prefix)
            expected = [r for r in source_rows if r["root"] == root and r["path"].startswith(prefix)]
            assert expected and result["restored_regular_files"] == len(expected)
            for row in expected:
                restored = target / row["root"] / Path(*bundle.safe_relative(row["path"]).parts)
                assert restored.stat().st_size == row["bytes"] and bundle.sha(restored) == row["sha256"], restored
            results.append({"case": name, **result, "all_restored_bytes_sha256_matched": True,
                            "source_asset_ids": [r["root"] + ":" + r["path"] for r in expected]})
            print(json.dumps({"case": name, "files": len(expected), "bytes": result["bytes"], "passed": True}), flush=True)
        assert len([r for r in expected]) == 2
        success = True
    finally:
        receipt = {"passed": success, "observed_utc": datetime.now(timezone.utc).isoformat(), "cases": results,
                   "scratch_preexisting": False, "scratch_directory": str(scratch), "generated_successful_test_copies_cleaned": False,
                   "original_assets_deleted_or_modified": False, "full_target_link_permission_restore_validated": False,
                   "model_or_result_array_loading_performed": False}
        if success:
            resolved = scratch.resolve()
            assert resolved.parent == PHASE.resolve() and resolved.is_relative_to(REPO.resolve())
            # Only successful, byte-verified, self-created scratch copies are removable.
            shutil.rmtree(resolved)
            receipt["generated_successful_test_copies_cleaned"] = True
        (PHASE / "RESTORE_CHECKS.json").write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
